#!/usr/bin/env python
"""Generate Proton icon replacements for Firefox's own pages (Settings, Add-ons, ...).

Firefox ships each Nova-aware icon as one SVG holding two drawings: <g class="proton"> and
<g class="nova">, switched inside the SVG by @media -moz-pref("browser.nova.enabled"). CSS in
userContent.css cannot reach that switch, but an <img src="chrome://..."> can be repointed with
`content: url(...)`. This script writes, for every such icon, a Proton-only SVG plus the CSS rule.

Usage (extract Firefox's two omni.ja files first; they are zip archives):
    Expand-Archive <Firefox>\\omni.ja         <dir>\\toolkit
    Expand-Archive <Firefox>\\browser\\omni.ja <dir>\\browser
    python gen_content_icons.py <dir>\\toolkit <dir>\\browser <profile>\\chrome

Writes <profile>\\chrome\\proton-content\\*.svg and <profile>\\chrome\\proton-content-icons.css.
Re-run after a Firefox update that changes icons.
"""
import re
import sys
from pathlib import Path

SWITCH = "browser.nova.enabled"
STYLE = re.compile(r"<style>.*?</style>\s*", re.S)
NOVA_G = re.compile(r'<g class="nova"[^>]*>.*?</g>\s*', re.S)


def proton_only(svg: str) -> str | None:
    if SWITCH not in svg or '<g class="proton"' not in svg:
        return None
    svg = STYLE.sub("", svg)
    svg = NOVA_G.sub("", svg)
    return svg


def chrome_url(root: Path, path: Path, package_root: str) -> str | None:
    """Map a file under <root>/chrome/<package_root>/skin/classic/<skin>/<rel> to its chrome:// URL."""
    base = root / "chrome" / package_root / "skin" / "classic"
    try:
        rel = path.relative_to(base)
    except ValueError:
        return None
    skin, *rest = rel.parts
    return f"chrome://{skin}/skin/{'/'.join(rest)}"


def main(toolkit: Path, browser: Path, out: Path) -> None:
    icons = out / "proton-content"
    icons.mkdir(parents=True, exist_ok=True)
    rules = []
    for root, package in ((toolkit, "toolkit"), (browser, "browser")):
        skin_root = root / "chrome" / package / "skin" / "classic"
        for f in sorted(skin_root.rglob("*.svg")):
            svg = proton_only(f.read_text(encoding="utf-8", errors="replace"))
            url = chrome_url(root, f, package)
            if svg is None or url is None:
                continue
            name = url.replace("chrome://", "").replace("/skin/", "__").replace("/", "_")
            (icons / name).write_text(svg, encoding="utf-8", newline="\n")
            rules.append((url, name))
    lines = [
        "/* Generated by tools/gen_content_icons.py: Proton drawings for icons on Firefox's own pages. */",
        '@-moz-document url-prefix("about:"), url-prefix("chrome:") {',
    ]
    for url, name in rules:
        lines.append(f'  :is(img, image)[src="{url}"] {{ content: url("proton-content/{name}") !important; }}')
    lines.append("}")
    (out / "proton-content-icons.css").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(rules)} icons written to {icons} and proton-content-icons.css")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*(Path(a) for a in sys.argv[1:]))
